import type { ItemDef } from '../engine/items/types';

/**
 * Every item in the game. Icons are 16 x 16 atlas frames (`item/...`). Sell prices are for the shipping bin;
 * seeds cannot be sold. See the art contract in GAME_DESIGN.md.
 */

const seed = (id: string, name: string, plants: string, icon: string): ItemDef => ({
  id,
  name,
  description: `Plant in tilled soil to grow ${name.replace(' seeds', '').toLowerCase()}.`,
  kind: 'seed',
  icon,
  maxStack: 99,
  sellPrice: 0,
  plants,
});

