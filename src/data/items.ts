/** A piece of furniture: not for sale to a shop (it is worth nothing to anyone but you), placed in the farmhouse with the use key. */
const furniture = (id: string, name: string, description: string): ItemDef => ({
  id,
  name,
  description,
  kind: 'furniture',
  icon: `item/${id}`,
  maxStack: 9,
  sellPrice: 0,
  places: id,
});

